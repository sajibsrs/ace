#!/bin/sh
# Regenerates shader.ace from shader.frag, compiled to SPIR-V by glslc, and
# shader.metal, kept as the source text Metal compiles at run time.
set -eu
cd "$(dirname "$0")"

spirv=$(mktemp)
trap 'rm -f "$spirv"' EXIT
glslc -fshader-stage=fragment -O -o "$spirv" shader.frag

# One `pub NAME: const [N]u8` table of a file's bytes, 16 to a row.
table() {
    printf 'pub %s: const [%d]u8 = [\n' "$1" "$(($(wc -c <"$2")))"
    od -An -v -tx1 "$2" | sed 's/[[:space:]]*\([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/    /; s/ $//'
    printf ']\n'
}

{
    printf '/* The fragment shader of main.ace in both formats SDL may ask for.\n'
    printf ' * Generated by shader.sh from shader.frag and shader.metal; edit those.\n'
    printf ' */\n\n'
    printf '// shader.frag as SPIR-V, for Vulkan.\n'
    table SPIRV "$spirv"
    printf '\n// shader.metal as its own text, for Metal.\n'
    table MSL shader.metal
} >shader.ace
